test('pre-2007 substitute only applies to the next day', () => {
	// 1992-05-03 (Sun) → 5/4 becomes 振替休日; 5/5 is こどもの日 already.
	const h = getHolidays(1992);
	assert.equal(h.get('1992-05-04'), '振替休日');
	assert.equal(h.get('1992-05-06'), undefined);
});

test('no substitute holidays before 1973-04-12', () => {
	// 1973-02-11 (Sun) had no substitute; 1973-04-29 (Sun) did.
	const h = getHolidays(1973);
	assert.equal(h.get('1973-02-12'), undefined);
	assert.equal(h.get('1973-04-30'), '振替休日');
});

test('showa era 4/29 naming', () => {
	assert.equal(getHolidays(1988).get('1988-04-29'), '天皇誕生日');
	assert.equal(getHolidays(1989).get('1989-04-29'), 'みどりの日');
	assert.equal(getHolidays(1989).get('1989-12-23'), '天皇誕生日');
	assert.equal(getHolidays(2007).get('2007-04-29'), '昭和の日');
});
